def collect_catalog_charts(env: EnvironmentTree) -> tuple[CatalogChartPull, ...]:
    """List every Helm chart pulled by Argo CD Applications using local YAML reads only."""
    documents = sorted(discover_argocd_applications(env.application_dirs).items())
    charts = [
        CatalogChartPull(
            application=app_name,
            chart=str(source.get("chart") or ""),
            repo_url=str(source.get("repoURL") or ""),
            version=str(source.get("targetRevision") or ""),
        )
        for app_name, doc in documents
        for source in application_sources(doc)
        if "chart" in source
    ]
    return tuple(charts)


def load_catalog_entries(path: Path) -> tuple[CatalogServiceEntry, ...]:
    """Load and validate `[[service]]` tables from `catalog.toml`."""
    if not path.is_file():
        raise CatalogError(f"Catalog data file not found: {path}")
    try:
        raw = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise CatalogError(f"Cannot read catalog file {path}: {exc}") from exc
    raw_services = raw.get("service")
    if not isinstance(raw_services, list):
        raise CatalogError(f"{path}: expected `[[service]]` array tables.")
    entries: list[CatalogServiceEntry] = []
    for entry in raw_services:
        try:
            entries.append(CatalogServiceEntry.model_validate(entry))
        except ValidationError as exc:
            raise CatalogError(f"{path}: invalid service entry: {exc}") from exc
    return tuple(entries)


def _sub(mapping: Mapping[str, Any], key: str) -> Mapping[str, Any]:
    """Return nested mapping at `key`, or an empty dict."""
    value = mapping.get(key)
    return value if isinstance(value, Mapping) else {}


def _str_dict(mapping: Any) -> dict[str, str]:
    """Extract string key/value pairs from a mapping node."""
    if not isinstance(mapping, Mapping):
        return {}
    return {str(k): str(v) for k, v in mapping.items()}


def _container_summary(raw: Mapping[str, Any]) -> ContainerSpecSummary:
    """Summarize one Kubernetes container block."""
    resources = _sub(raw, "resources")
    requests = _sub(resources, "requests")
    limits = _sub(resources, "limits")
    return ContainerSpecSummary(
        name=str(raw.get("name") or ""),
        image=str(raw.get("image") or ""),
        cpu_request=str(requests["cpu"]) if "cpu" in requests else None,
        memory_request=str(requests["memory"]) if "memory" in requests else None,
        memory_limit=str(limits["memory"]) if "memory" in limits else None,
        liveness_probe=bool(raw.get("livenessProbe")),
        readiness_probe=bool(raw.get("readinessProbe")),
        startup_probe=bool(raw.get("startupProbe")),
    )


def _pod_spec_for(kind: str, spec: Mapping[str, Any]) -> Mapping[str, Any]:
    """Return the underlying pod template spec for standard Kubernetes workload kinds."""
    if kind == "CronJob":
        tmpl = _sub(_sub(_sub(spec, "jobTemplate"), "spec"), "template")
    else:
        tmpl = _sub(spec, "template")
    return _sub(tmpl, "spec")


def _pod_labels_for(kind: str, meta: Mapping[str, Any], spec: Mapping[str, Any]) -> dict[str, str]:
    """Merge metadata labels and pod template labels for Service selector matching."""
    labels = _str_dict(meta.get("labels"))
    if kind == "CronJob":
        tmpl = _sub(_sub(_sub(spec, "jobTemplate"), "spec"), "template")
    else:
        tmpl = _sub(spec, "template")
    labels.update(_str_dict(_sub(tmpl, "metadata").get("labels")))
    return labels


def _update_strategy_for(kind: str, spec: Mapping[str, Any]) -> str | None:
    """Extract rollout or concurrency strategy for a workload kind."""
    if kind == "Deployment":
        val = _sub(spec, "strategy").get("type")
        return str(val) if val else None
    if kind in ("StatefulSet", "DaemonSet"):
        val = _sub(spec, "updateStrategy").get("type")
        return str(val) if val else None
    if kind == "Mattermost":
        val = _sub(spec, "deploymentTemplate").get("deploymentStrategyType")
        return str(val) if val else None
    if kind in ("CronJob", "CronWorkflow") and spec.get("concurrencyPolicy"):
        return str(spec["concurrencyPolicy"])
    return None


def _operator_containers(kind: str, spec: Mapping[str, Any]) -> tuple[ContainerSpecSummary, ...]:
    """Synthesize container summaries for CloudNativePG `Cluster` and `Mattermost` CRDs."""
    if kind == "Cluster":
        res = _sub(spec, "resources")
        req = _sub(res, "requests")
        lim = _sub(res, "limits")
        if not req and not lim and not spec.get("imageName"):
            return ()
        return (
            ContainerSpecSummary(
                name="postgres",
                image=str(spec.get("imageName") or ""),
                cpu_request=str(req["cpu"]) if "cpu" in req else None,
                memory_request=str(req["memory"]) if "memory" in req else None,
                memory_limit=str(lim["memory"]) if "memory" in lim else None,
                liveness_probe=False,
                readiness_probe=False,
                startup_probe=False,
            ),
        )
    if kind == "Mattermost":
        res = _sub(_sub(spec, "scheduling"), "resources")
        req = _sub(res, "requests")
        lim = _sub(res, "limits")
        img = str(spec.get("image") or "")
        ver = str(spec.get("version") or "")
        image = f"{img}:{ver}" if img and ver else img
        return (
            ContainerSpecSummary(
                name="mattermost",
                image=image,
                cpu_request=str(req["cpu"]) if "cpu" in req else None,
                memory_request=str(req["memory"]) if "memory" in req else None,
                memory_limit=str(lim["memory"]) if "memory" in lim else None,
                liveness_probe=False,
                readiness_probe=False,
                startup_probe=False,
            ),
        )
    return ()


def _parse_workload(app_name: str, default_ns: str, doc: Mapping[str, Any]) -> WorkloadSummary:
    """Build a `WorkloadSummary` from a Kubernetes workload or operator manifest."""
    kind = str(doc["kind"])
    meta = _sub(doc, "metadata")
    spec = _sub(doc, "spec")
    name = str(meta.get("name") or "")
    ns = str(meta.get("namespace") or default_ns)
    labels = _pod_labels_for(kind, meta, spec)

    replicas: int | None = None
    if kind == "Cluster" and isinstance(spec.get("instances"), int):
        replicas = int(spec["instances"])
    elif isinstance(spec.get("replicas"), int):
        replicas = int(spec["replicas"])

    homepage_desc: str | None = None
    if kind == "Mattermost":
        ing_anns = _str_dict(_sub(spec, "ingress").get("annotations"))
        homepage_desc = ing_anns.get(HOMEPAGE_DESCRIPTION_ANNOTATION)

    if kind in ("Cluster", "Mattermost"):
        containers = _operator_containers(kind, spec)
        grace = None
        prio = None
        runtime = None
    else:
        pod_spec = _pod_spec_for(kind, spec)
        raw_containers = pod_spec.get("containers")
        containers = tuple(
            _container_summary(c)
            for c in (raw_containers if isinstance(raw_containers, list) else [])
            if isinstance(c, Mapping)
        )
        raw_grace = pod_spec.get("terminationGracePeriodSeconds")
        grace = int(raw_grace) if isinstance(raw_grace, int) else None
        prio = str(pod_spec["priorityClassName"]) if pod_spec.get("priorityClassName") else None
        runtime = str(pod_spec["runtimeClassName"]) if pod_spec.get("runtimeClassName") else None

    return WorkloadSummary(
        application=app_name,
        kind=kind,
        name=name,
        namespace=ns,
        replicas=replicas,
        update_strategy=_update_strategy_for(kind, spec),
        termination_grace_period_seconds=grace,
        priority_class=prio,
        runtime_class=runtime,
        containers=containers,
        labels=tuple(sorted(labels.items())),
        homepage_description=homepage_desc,
    )


def _extract_stores(app_name: str, default_ns: str, doc: Mapping[str, Any]) -> list[StoreSummary]:
    """Extract PVC, StatefulSet `volumeClaimTemplates`, CloudNativePG `Cluster`, and `ScheduledBackup`."""
    kind = str(doc.get("kind") or "")
    meta = _sub(doc, "metadata")
    spec = _sub(doc, "spec")
    name = str(meta.get("name") or "")
    ns = str(meta.get("namespace") or default_ns)

    if kind == "PersistentVolumeClaim":
        req = _sub(_sub(spec, "resources"), "requests")
        modes = spec.get("accessModes")
        return [
            StoreSummary(
                application=app_name,
                kind="PersistentVolumeClaim",
                name=name,
                namespace=ns,
                storage_class=(
                    str(spec["storageClassName"]) if spec.get("storageClassName") else None
                ),
                size=str(req["storage"]) if "storage" in req else None,
                access_modes=tuple(str(m) for m in modes) if isinstance(modes, list) else (),
            )
        ]

    if kind == "StatefulSet":
        vcts = spec.get("volumeClaimTemplates")
        if not isinstance(vcts, list):
            return []
        out: list[StoreSummary] = []
        for vct in vcts:
            if not isinstance(vct, Mapping):
                continue
            v_meta = _sub(vct, "metadata")
            v_spec = _sub(vct, "spec")
            v_req = _sub(_sub(v_spec, "resources"), "requests")
            v_modes = v_spec.get("accessModes")
            vct_name = str(v_meta.get("name") or "claim")
            out.append(
                StoreSummary(
                    application=app_name,
                    kind="VolumeClaimTemplate",
                    name=f"{name}/{vct_name}",
                    namespace=ns,
                    storage_class=(
                        str(v_spec["storageClassName"]) if v_spec.get("storageClassName") else None
                    ),
                    size=str(v_req["storage"]) if "storage" in v_req else None,
                    access_modes=(
                        tuple(str(m) for m in v_modes) if isinstance(v_modes, list) else ()
                    ),
                )
            )
        return out

    if kind == "Cluster":
        stor = _sub(spec, "storage")
        return [
            StoreSummary(
                application=app_name,
                kind="Cluster",
                name=name,
                namespace=ns,
                storage_class=str(stor["storageClass"]) if stor.get("storageClass") else None,
                size=str(stor["size"]) if stor.get("size") else None,
                instances=int(spec["instances"])
                if isinstance(spec.get("instances"), int)
                else None,
                cluster=name,
            )
        ]

    if kind == "ScheduledBackup":
        clust = _sub(spec, "cluster")
        return [
            StoreSummary(
                application=app_name,
                kind="ScheduledBackup",
                name=name,
                namespace=ns,
                storage_class=None,
                size=None,
                schedule=str(spec["schedule"]) if spec.get("schedule") else None,
                cluster=str(clust["name"]) if clust.get("name") else None,
            )
        ]

    return []


def _parse_cluster_class(doc: Mapping[str, Any]) -> ClusterClassSummary:
    """Build a `ClusterClassSummary` for PriorityClass, RuntimeClass, or StorageClass."""
    kind = str(doc["kind"])
    meta = _sub(doc, "metadata")
    name = str(meta.get("name") or "")
    if kind == "PriorityClass":
        detail = f"value={doc.get('value', '')}"
        if doc.get("globalDefault"):
            detail += ", globalDefault=true"
    elif kind == "RuntimeClass":
        detail = f"handler={doc.get('handler', '')}"
    else:
        parts = [f"provisioner={doc.get('provisioner', '')}"]
        if doc.get("reclaimPolicy"):
            parts.append(f"reclaim={doc['reclaimPolicy']}")
        if doc.get("volumeBindingMode"):
            parts.append(f"binding={doc['volumeBindingMode']}")
        detail = ", ".join(parts)
    return ClusterClassSummary(kind=kind, name=name, detail=detail)


def _ingress_backend_services(
    default_ns: str, spec: Mapping[str, Any]
) -> tuple[tuple[str, str], ...]:
    """Collect `(namespace, service_name)` pairs referenced by an `Ingress` resource."""
    refs: list[tuple[str, str]] = []
    default_backend = spec.get("defaultBackend")
    if isinstance(default_backend, Mapping) and isinstance(default_backend.get("service"), Mapping):
        svc_name = default_backend["service"].get("name")
        if svc_name:
            refs.append((default_ns, str(svc_name)))
    for rule in spec.get("rules") or []:
        if not isinstance(rule, Mapping) or not isinstance(rule.get("http"), Mapping):
            continue
        for path in rule["http"].get("paths") or []:
            if not isinstance(path, Mapping) or not isinstance(path.get("backend"), Mapping):
                continue
            svc = path["backend"].get("service")
            if isinstance(svc, Mapping) and svc.get("name"):
                refs.append((default_ns, str(svc["name"])))
    return tuple(dict.fromkeys(refs))


def _ingressroute_backend_services(
    default_ns: str, spec: Mapping[str, Any]
) -> tuple[tuple[str, str], ...]:
    """Collect `(namespace, service_name)` pairs referenced by a Traefik `IngressRoute`."""
    refs: list[tuple[str, str]] = []
    for route in spec.get("routes") or []:
        if not isinstance(route, Mapping):
            continue
        for svc in route.get("services") or []:
            if not isinstance(svc, Mapping) or svc.get("kind") == "TraefikService":
                continue
            svc_name = svc.get("name")
            if svc_name:
                svc_ns = str(svc.get("namespace") or default_ns)
                refs.append((svc_ns, str(svc_name)))
    return tuple(dict.fromkeys(refs))


def _parse_ui_binding(default_ns: str, doc: Mapping[str, Any]) -> _UiBinding | None:
    """Extract `gethomepage.dev/description` and its target Services from an Ingress/IngressRoute."""
    kind = str(doc.get("kind") or "")
    if kind not in ("Ingress", "IngressRoute"):
        return None
    meta = _sub(doc, "metadata")
    anns = _str_dict(meta.get("annotations"))
    description = anns.get(HOMEPAGE_DESCRIPTION_ANNOTATION)
    if not description:
        return None
    ns = str(meta.get("namespace") or default_ns)
    name = str(meta.get("name") or "")
    spec = _sub(doc, "spec")
    refs = (
        _ingress_backend_services(ns, spec)
        if kind == "Ingress"
        else _ingressroute_backend_services(ns, spec)
    )
    return _UiBinding(namespace=ns, name=name, description=description, services=refs)


def _render_app_objects(
    trees: SourceTrees, app_name: str, app_doc: dict[str, Any], workdir: Path
) -> _AppObjects:
    """Render an Argo CD Application and extract its Kubernetes objects."""
    spec = app_doc.get("spec") or {}
    default_ns = str((spec.get("destination") or {}).get("namespace") or "default")
    workloads: list[WorkloadSummary] = []
    stores: list[StoreSummary] = []
    cluster_classes: list[ClusterClassSummary] = []
    service_selectors: dict[tuple[str, str], dict[str, str]] = {}
    ui_bindings: list[_UiBinding] = []

    for rendered, _ in application_renders(trees, app_name, app_doc, workdir):
        for doc in yaml.load_all(rendered, Loader=YAML_SAFE_LOADER):
            if not isinstance(doc, Mapping):
                continue
            kind = str(doc.get("kind") or "")
            if kind in _WORKLOAD_KINDS:
                workloads.append(_parse_workload(app_name, default_ns, doc))
            if kind == "Service":
                meta = _sub(doc, "metadata")
                svc_name = str(meta.get("name") or "")
                svc_ns = str(meta.get("namespace") or default_ns)
                svc_spec = _sub(doc, "spec")
                selector = _str_dict(svc_spec.get("selector"))
                if svc_name and selector:
                    service_selectors[(svc_ns, svc_name)] = selector
            stores.extend(_extract_stores(app_name, default_ns, doc))
            if kind in _CLUSTER_CLASS_KINDS:
                cluster_classes.append(_parse_cluster_class(doc))
            if kind in _UI_KINDS:
                binding = _parse_ui_binding(default_ns, doc)
                if binding is not None:
                    ui_bindings.append(binding)

    return _AppObjects(
        application=app_name,
        workloads=tuple(workloads),
        stores=tuple(stores),
        cluster_classes=tuple(cluster_classes),
        service_selectors=service_selectors,
        ui_bindings=tuple(ui_bindings),
    )


def _match_entry_workloads(
    entry: CatalogServiceEntry,
    rendered_apps: frozenset[str],
    all_workloads: tuple[WorkloadSummary, ...],
) -> tuple[WorkloadSummary, ...]:
    """Return rendered workloads matching one catalog entry's applications and glob filters."""
    missing_apps = [app for app in entry.applications if app not in rendered_apps]
    if missing_apps:
        raise CatalogError(
            f"Service '{entry.name}' names missing Application(s): {', '.join(missing_apps)}."
        )
    app_set = frozenset(entry.applications)
    pool = [w for w in all_workloads if w.application in app_set]
    if not entry.workloads:
        return tuple(pool)
    matched: list[WorkloadSummary] = []
    for pattern in entry.workloads:
        hits = [w for w in pool if fnmatchcase(w.name, pattern)]
        if not hits:
            raise CatalogError(
                f"Service '{entry.name}' names workload '{pattern}' not found in "
                f"Application(s) {', '.join(entry.applications)}."
            )
        for hit in hits:
            if hit not in matched:
                matched.append(hit)
    return tuple(matched)


def _claim_workloads(
    entries: tuple[CatalogServiceEntry, ...],
    rendered_apps: frozenset[str],
    all_workloads: tuple[WorkloadSummary, ...],
) -> tuple[dict[str, tuple[WorkloadSummary, ...]], dict[tuple[str, str, str], set[str]]]:
    """Assign rendered workloads to catalog entries and reject unclaimed or missing targets."""
    claimed_by_entry: dict[str, tuple[WorkloadSummary, ...]] = {}
    workload_owners: dict[tuple[str, str, str], set[str]] = {}

    for entry in entries:
        matched = _match_entry_workloads(entry, rendered_apps, all_workloads)
        claimed_by_entry[entry.name] = matched
        for w in matched:
            workload_owners.setdefault((w.application, w.namespace, w.name), set()).add(entry.name)

    unclaimed = [
        w for w in all_workloads if (w.application, w.namespace, w.name) not in workload_owners
    ]
    if unclaimed:
        names = ", ".join(f"{w.kind}/{w.name} ({w.application})" for w in unclaimed)
        raise CatalogError(f"Unclaimed workload(s) have no entry in catalog.toml: {names}")

    return claimed_by_entry, workload_owners


def _selector_matching_owners(
    svc_ns: str,
    selector: dict[str, str],
    all_workloads: tuple[WorkloadSummary, ...],
    workload_owners: dict[tuple[str, str, str], set[str]],
) -> set[str]:
    """Return catalog service names whose claimed workloads satisfy a Service selector."""
    owners: set[str] = set()
    for w in all_workloads:
        if w.namespace != svc_ns:
            continue
        labels = dict(w.labels)
        if all(labels.get(k) == v for k, v in selector.items()):
            owners.update(workload_owners[(w.application, w.namespace, w.name)])
    return owners


def _collect_ui_descriptions(
    entries: tuple[CatalogServiceEntry, ...],
    claimed_by_entry: dict[str, tuple[WorkloadSummary, ...]],
    workload_owners: dict[tuple[str, str, str], set[str]],
    all_workloads: tuple[WorkloadSummary, ...],
    service_selectors: Mapping[tuple[str, str], dict[str, str]],
    ui_bindings: Iterable[_UiBinding],
) -> dict[str, dict[tuple[str, str], str]]:
    """Gather UI annotation descriptions mapped to `(source_namespace, source_name)` per service."""
    collected: dict[str, dict[tuple[str, str], str]] = {e.name: {} for e in entries}
    for entry in entries:
        for w in claimed_by_entry[entry.name]:
            if w.homepage_description:
                collected[entry.name][(w.namespace, w.name)] = w.homepage_description
    for binding in ui_bindings:
        for svc_ns, svc_name in binding.services:
            selector = service_selectors.get((svc_ns, svc_name))
            if not selector:
                continue
            for owner in _selector_matching_owners(
                svc_ns, selector, all_workloads, workload_owners
            ):
                collected[owner][(binding.namespace, binding.name)] = binding.description
    return collected


def _resolve_ui_descriptions(
    entries: tuple[CatalogServiceEntry, ...],
    claimed_by_entry: dict[str, tuple[WorkloadSummary, ...]],
    workload_owners: dict[tuple[str, str, str], set[str]],
    all_workloads: tuple[WorkloadSummary, ...],
    service_selectors: Mapping[tuple[str, str], dict[str, str]],
    ui_bindings: Iterable[_UiBinding],
) -> dict[str, tuple[str, ...]]:
    """Resolve `gethomepage.dev/description` annotations per service and reject duplicates."""
    collected = _collect_ui_descriptions(
        entries, claimed_by_entry, workload_owners, all_workloads, service_selectors, ui_bindings
    )
    resolved: dict[str, tuple[str, ...]] = {}
    for entry in entries:
        ui_items = sorted(collected[entry.name].items(), key=lambda pair: pair[0])
        ui_texts = tuple(text for _, text in ui_items)
        if ui_texts and entry.description:
            raise CatalogError(
                f"Service '{entry.name}' declares a description in both catalog.toml and a UI "
                f"`{HOMEPAGE_DESCRIPTION_ANNOTATION}` annotation."
            )
        if ui_texts:
            resolved[entry.name] = ui_texts
        elif entry.description:
            resolved[entry.name] = (entry.description,)
        else:
            resolved[entry.name] = ("none",)
    return resolved


def _load_and_join_slos(
    env: EnvironmentTree, entries: tuple[CatalogServiceEntry, ...]
) -> tuple[dict[str, tuple[SloSummary, ...]], tuple[SloSummary, ...]]:
    """Load Sloth SLO specs under `devops/monitoring/slos/` and join by `service` name."""
    slos_dir = env.path("devops/monitoring/slos")
    if not slos_dir.is_dir():
        return {e.name: () for e in entries}, ()
    specs: list[SloSpec] = load_slo_specs(slos_dir)
    service_names = {e.name for e in entries}
    grouped: dict[str, list[SloSummary]] = {e.name: [] for e in entries}
    ordered: list[SloSummary] = []

    for spec in specs:
        if spec.service not in service_names:
            raise CatalogError(
                f"Sloth spec {spec.path} names unknown service '{spec.service}' not in catalog.toml."
            )
        objective = f"{format(spec.objective.normalize(), 'f')}%"
        budget = f"{format((spec.error_budget * 100).normalize(), 'f')}%"
        summary = SloSummary(
            service=spec.service,
            name=spec.name,
            objective=objective,
            error_budget=budget,
            window=f"{SLO_WINDOW_DAYS}d",
            sli=f"{spec.error_query} / {spec.total_query}",
            description=spec.description,
        )
        grouped[spec.service].append(summary)
        ordered.append(summary)

    return {k: tuple(v) for k, v in grouped.items()}, tuple(ordered)


def _load_and_join_dashboards(
    env: EnvironmentTree,
    entries: tuple[CatalogServiceEntry, ...],
    workload_owners: dict[tuple[str, str, str], set[str]],
) -> dict[str, tuple[DashboardSummary, ...]]:
    """Load `monitoring/dashboards/services.toml` and join dashboards by `(namespace, workload)`."""
    specs_file = env.dashboards / DASHBOARD_SPEC_FILE
    grouped: dict[str, list[DashboardSummary]] = {e.name: [] for e in entries}
    if not specs_file.is_file():
        return {k: () for k in grouped}
    specs: list[ServiceSpec] = load_dashboard_specs(specs_file)

    for spec in specs:
        owners: set[str] = set()
        for (_app_name, ns, w_name), entry_owners in workload_owners.items():
            if ns == spec.namespace and w_name == spec.workload:
                owners.update(entry_owners)
        if not owners:
            raise CatalogError(
                f"Dashboard '{spec.uid}' in {specs_file} targets unknown workload "
                f"'{spec.namespace}/{spec.workload}'."
            )
        dash = DashboardSummary(
            uid=spec.uid,
            title=spec.title,
            namespace=spec.namespace,
            workload=spec.workload,
        )
        for owner in sorted(owners):
            grouped[owner].append(dash)

    return {k: tuple(v) for k, v in grouped.items()}


def _stores_for_service(
    entry: CatalogServiceEntry,
    workloads: tuple[WorkloadSummary, ...],
    all_stores: tuple[StoreSummary, ...],
) -> tuple[StoreSummary, ...]:
    """Associate rendered stores with a service entry cleanly."""
    app_set = frozenset(entry.applications)
    workload_names = {w.name for w in workloads}
    matched: list[StoreSummary] = []
    for store in all_stores:
        if store.application not in app_set:
            continue
        if not entry.workloads:
            matched.append(store)
            continue
        base = store.name.partition("/")[0]
        if (
            store.name == entry.name
            or base in workload_names
            or any(fnmatchcase(store.name, p) for p in entry.workloads)
            or (store.cluster is not None and store.cluster in workload_names)
        ):
            matched.append(store)
    return tuple(matched)


def build_catalog(env: EnvironmentTree, *, origin_url: str | None = None) -> ServiceCatalog:
    """Render all Argo CD Applications of `env`, join metadata, validate, and return catalog."""
    entries = load_catalog_entries(env.path(CATALOG_TOML_NAME))
    documents = sorted(discover_argocd_applications(env.application_dirs).items())
    origin = normalize_git_url(origin_url or repository_origin(env.repo))

    with tempfile.TemporaryDirectory(prefix="k8s-catalog-") as tmp:
        trees = SourceTrees(env.repo, origin, Path(tmp) / "sources")
        with ThreadPoolExecutor(max_workers=_WORKERS) as pool:
            app_objects = list(
                pool.map(
                    lambda item: _render_app_objects(trees, item[0], item[1], Path(tmp)),
                    documents,
                )
            )

    rendered_apps = frozenset(obj.application for obj in app_objects)
    all_workloads = tuple(w for obj in app_objects for w in obj.workloads)
    all_stores = tuple(s for obj in app_objects for s in obj.stores)

    seen_classes: dict[tuple[str, str], ClusterClassSummary] = {}
    service_selectors: dict[tuple[str, str], dict[str, str]] = {}
    ui_bindings: list[_UiBinding] = []
    for obj in app_objects:
        for cc in obj.cluster_classes:
            seen_classes[(cc.kind, cc.name)] = cc
        service_selectors.update(obj.service_selectors)
        ui_bindings.extend(obj.ui_bindings)
    all_classes = tuple(
        seen_classes[k] for k in sorted(seen_classes, key=lambda pair: (pair[0], pair[1]))
    )

    claimed_by_entry, workload_owners = _claim_workloads(entries, rendered_apps, all_workloads)
    descriptions = _resolve_ui_descriptions(
        entries, claimed_by_entry, workload_owners, all_workloads, service_selectors, ui_bindings
    )
    slos_by_service, all_slos = _load_and_join_slos(env, entries)
    dashboards_by_service = _load_and_join_dashboards(env, entries, workload_owners)

    resolved_services = tuple(
        ResolvedService(
            entry=entry,
            descriptions=descriptions[entry.name],
            namespaces=tuple(sorted({w.namespace for w in claimed_by_entry[entry.name]})),
            workloads=claimed_by_entry[entry.name],
            stores=_stores_for_service(entry, claimed_by_entry[entry.name], all_stores),
            slos=slos_by_service[entry.name],
            dashboards=dashboards_by_service[entry.name],
        )
        for entry in entries
    )

    return ServiceCatalog(
        services=resolved_services,
        slos=all_slos,
        workloads=all_workloads,
        stores=all_stores,
        cluster_classes=all_classes,
    )


def _cell(value: str) -> str:
    """Escape pipes in Markdown table cells."""
    return value.replace("|", "\\|")


def _replicas_text(workloads: tuple[WorkloadSummary, ...]) -> str:
    """Summarize total instances across a service's workloads."""
    counts = [str(w.replicas) for w in workloads if w.replicas is not None]
    return ", ".join(counts) if counts else "-"


def _container_text(containers: tuple[ContainerSpecSummary, ...]) -> str:
    """Summarize container resources and probes for the Workloads table."""
    if not containers:
        return "-"
    parts: list[str] = []
    for c in containers:
        probes = [
            tag
            for tag, flag in (
                ("L", c.liveness_probe),
                ("R", c.readiness_probe),
                ("S", c.startup_probe),
            )
            if flag
        ]
        probe_str = f" probes={''.join(probes)}" if probes else ""
        parts.append(
            f"{c.name}(req={c.cpu_request or '-'}/{c.memory_request or '-'},"
            f"lim={c.memory_limit or '-'}{probe_str})"
        )
    return "; ".join(parts)


def render_catalog_markdown(catalog: ServiceCatalog) -> str:
    """Render `ServiceCatalog` into the generated `CATALOG.md` Markdown format."""
    lines: list[str] = [
        "# Service Catalog",
        "",
        CATALOG_GENERATED_LINE,
        "",
        "## Services",
        "",
        "| Service | Tier | Data class | Applications | Namespaces | Replicas | Stores | Dashboards | SLOs | Depends on | Description |",
        "| :--- | ---: | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
    ]

    for svc in catalog.services:
        stores_txt = ", ".join(f"{s.kind}/{s.name}" for s in svc.stores) or "-"
        dash_txt = ", ".join(d.uid for d in svc.dashboards) or "none"
        slo_txt = ", ".join(f"{s.name} ({s.objective} / {s.window})" for s in svc.slos) or "none"
        deps_txt = ", ".join(svc.entry.depends_on) or "-"
        ns_txt = ", ".join(svc.namespaces) or "-"
        desc_txt = "<br>".join(_cell(line) for line in svc.descriptions)
        lines.append(
            f"| {_cell(svc.entry.name)} | {svc.entry.tier} | {_cell(svc.entry.data_class)} | "
            f"{_cell(', '.join(svc.entry.applications))} | {_cell(ns_txt)} | "
            f"{_cell(_replicas_text(svc.workloads))} | {_cell(stores_txt)} | "
            f"{_cell(dash_txt)} | {_cell(slo_txt)} | {_cell(deps_txt)} | {desc_txt} |"
        )

    lines.extend(["", "## SLOs", ""])
    if catalog.slos:
        lines.extend(
            [
                "| Service | Name | Objective | Error budget | Window | SLI | Description |",
                "| :--- | :--- | ---: | ---: | :--- | :--- | :--- |",
                *[
                    f"| {_cell(s.service)} | {_cell(s.name)} | {s.objective} | "
                    f"{s.error_budget} | {s.window} | `{_cell(s.sli)}` | {_cell(s.description)} |"
                    for s in catalog.slos
                ],
            ]
        )
    else:
        lines.append("No Sloth SLO specs defined.")

    lines.extend(
        [
            "",
            "## Workloads by Application",
            "",
            "| Application | Kind | Name | Namespace | Replicas | Strategy | Grace (s) | PriorityClass | RuntimeClass | Containers |",
            "| :--- | :--- | :--- | :--- | ---: | :--- | ---: | :--- | :--- | :--- |",
        ]
    )
    for w in catalog.workloads:
        rep = str(w.replicas) if w.replicas is not None else "-"
        grace = (
            str(w.termination_grace_period_seconds)
            if w.termination_grace_period_seconds is not None
            else "-"
        )
        lines.append(
            f"| {_cell(w.application)} | {_cell(w.kind)} | {_cell(w.name)} | "
            f"{_cell(w.namespace)} | {rep} | {_cell(w.update_strategy or '-')} | {grace} | "
            f"{_cell(w.priority_class or '-')} | {_cell(w.runtime_class or '-')} | "
            f"{_cell(_container_text(w.containers))} |"
        )

    lines.extend(["", "## Stores", ""])
    if catalog.stores:
        lines.extend(
            [
                "| Application | Kind | Name | Namespace | StorageClass | Size | Detail |",
                "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
            ]
        )
        for st in catalog.stores:
            detail_parts = [
                part
                for part in (
                    ",".join(st.access_modes) if st.access_modes else None,
                    f"instances={st.instances}" if st.instances is not None else None,
                    f"schedule={st.schedule}" if st.schedule else None,
                    f"cluster={st.cluster}" if st.cluster else None,
                )
                if part
            ]
            lines.append(
                f"| {_cell(st.application)} | {_cell(st.kind)} | {_cell(st.name)} | "
                f"{_cell(st.namespace)} | {_cell(st.storage_class or '-')} | "
                f"{_cell(st.size or '-')} | {_cell(', '.join(detail_parts) or '-')} |"
            )
    else:
        lines.append("No stores defined.")

    lines.extend(["", "## Cluster classes", ""])
    if catalog.cluster_classes:
        lines.extend(
            [
                "| Kind | Name | Detail |",
                "| :--- | :--- | :--- |",
                *[
                    f"| {_cell(cc.kind)} | {_cell(cc.name)} | {_cell(cc.detail)} |"
                    for cc in catalog.cluster_classes
                ],
            ]
        )
    else:
        lines.append("No cluster classes defined.")

    lines.append("")
    return "\n".join(lines)
