class CatalogServiceEntry(BaseModel):
    """One `[[service]]` entry from `catalog.toml`."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    name: str = Field(min_length=1)
    applications: tuple[str, ...] = Field(min_length=1)
