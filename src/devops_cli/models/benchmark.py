"""Pydantic data models for the AI benchmarking and peer-grading system."""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

BenchmarkCategory = Literal["security", "kubernetes", "architecture", "ci_cd", "infrastructure"]


class BenchmarkTask(BaseModel):
    """Definition of an evaluation task with reference criteria and rubric."""

    model_config = ConfigDict(frozen=True)

    id: str
    title: str
    category: BenchmarkCategory
    prompt: str
    expected_solution: str
    evaluation_rubric: str
    weight: float = Field(default=1.0, ge=0.1, le=5.0)


class TaskResponse(BaseModel):
    """Response generated by a candidate model for a specific task."""

    task_id: str
    model: str
    provider: str
    server: str = ""
    response: str
    duration_seconds: float = Field(default=0.0, ge=0.0)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))


class PeerGrade(BaseModel):
    """Score and assessment given by an evaluator model to a candidate response."""

    task_id: str
    candidate_model: str
    evaluator_model: str
    server: str = ""
    accuracy_score: float = Field(default=0.0, ge=0.0, le=10.0)
    security_score: float = Field(default=0.0, ge=0.0, le=10.0)
    completeness_score: float = Field(default=0.0, ge=0.0, le=10.0)
    clarity_score: float = Field(default=0.0, ge=0.0, le=10.0)
    total_score: float = Field(default=0.0, ge=0.0, le=40.0)
    percentage: float = Field(default=0.0, ge=0.0, le=100.0)
    strengths: list[str] = Field(default_factory=list)
    weaknesses: list[str] = Field(default_factory=list)
    feedback: str = ""


class ModelBenchmarkSummary(BaseModel):
    """Aggregated performance metrics for a candidate model across the benchmark suite."""

    model: str
    provider: str
    overall_percentage: float = Field(default=0.0, ge=0.0, le=100.0)
    accuracy_avg: float = Field(default=0.0, ge=0.0, le=10.0)
    security_avg: float = Field(default=0.0, ge=0.0, le=10.0)
    completeness_avg: float = Field(default=0.0, ge=0.0, le=10.0)
    clarity_avg: float = Field(default=0.0, ge=0.0, le=10.0)
    category_scores: dict[str, float] = Field(default_factory=dict)
    average_duration_seconds: float = Field(default=0.0, ge=0.0)
    grading_strictness_index: float = Field(
        default=0.0,
        description=(
            "Average difference between scores given to others vs consensus "
            "(positive = lenient, negative = strict)"
        ),
    )
    judge_weight: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description=(
            "Weight of this model when judging other models "
            "(proportional to its overall competence)"
        ),
    )
    valid_evaluations_count: int = Field(
        default=0,
        ge=0,
        description="Count of valid non-default evaluations included in scoring",
    )
    peer_only_percentage: float = Field(
        default=0.0,
        ge=0.0,
        le=100.0,
        description="Score computed purely from external peer evaluations (excluding self)",
    )
    self_preference_bias: float = Field(
        default=0.0,
        description="Average difference between self-assigned score and peer-assigned score",
    )


class BenchmarkReport(BaseModel):
    """Complete execution payload and leaderboards for a benchmark run."""

    session_id: str
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))
    models_evaluated: list[str]
    tasks_run: list[BenchmarkTask]
    responses: list[TaskResponse] = Field(default_factory=list)
    peer_grades: list[PeerGrade] = Field(default_factory=list)
    leaderboard: list[ModelBenchmarkSummary] = Field(default_factory=list)
    is_dry_run: bool = False
