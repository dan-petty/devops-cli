"""Pydantic data models for the AI benchmarking and peer-grading system."""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

BenchmarkCategory = Literal["security", "kubernetes", "architecture", "ci_cd", "infrastructure"]


class BenchmarkTask(BaseModel):
    """Definition of an evaluation task with reference criteria and rubric."""

    model_config = ConfigDict(frozen=True)

    id: str
    title: str
    category: BenchmarkCategory
    prompt: str
    expected_solution: str
    evaluation_rubric: str
    weight: float = Field(default=1.0, ge=0.1, le=5.0)


class TaskResponse(BaseModel):
    """Response generated by a candidate model for a specific task."""

    task_id: str
    model: str
    provider: str
    server: str = ""
    response: str
    duration_seconds: float = Field(default=0.0, ge=0.0)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))


class PeerGrade(BaseModel):
    """Score and assessment given by an evaluator model to a candidate response."""

    task_id: str
    candidate_model: str
    evaluator_model: str
    server: str = ""
    accuracy_score: float = Field(default=0.0, ge=0.0, le=10.0)
    security_score: float = Field(default=0.0, ge=0.0, le=10.0)
    completeness_score: float = Field(default=0.0, ge=0.0, le=10.0)
    clarity_score: float = Field(default=0.0, ge=0.0, le=10.0)
    total_score: float = Field(default=0.0, ge=0.0, le=40.0)
    percentage: float = Field(default=0.0, ge=0.0, le=100.0)
    strengths: list[str] = Field(default_factory=list)
    weaknesses: list[str] = Field(default_factory=list)
    feedback: str = ""


class ModelBenchmarkSummary(BaseModel):
    """Aggregated performance metrics for a candidate model across the benchmark suite."""

    model: str
    provider: str
    overall_percentage: float = Field(default=0.0, ge=0.0, le=100.0)
    accuracy_avg: float = Field(default=0.0, ge=0.0, le=10.0)
    security_avg: float = Field(default=0.0, ge=0.0, le=10.0)
    completeness_avg: float = Field(default=0.0, ge=0.0, le=10.0)
    clarity_avg: float = Field(default=0.0, ge=0.0, le=10.0)
    category_scores: dict[str, float] = Field(default_factory=dict)
    average_duration_seconds: float = Field(default=0.0, ge=0.0)
    grading_strictness_index: float = Field(
        default=0.0,
        description=(
            "Average difference between scores given to others vs consensus "
            "(positive = lenient, negative = strict)"
        ),
    )
    judge_weight: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description=(
            "Weight of this model when judging other models "
            "(proportional to its overall competence)"
        ),
    )
    valid_evaluations_count: int = Field(
        default=0,
        ge=0,
        description="Count of valid non-default evaluations included in scoring",
    )
    peer_only_percentage: float = Field(
        default=0.0,
        ge=0.0,
        le=100.0,
        description="Score computed purely from external peer evaluations (excluding self)",
    )
    self_preference_bias: float = Field(
        default=0.0,
        description="Average difference between self-assigned score and peer-assigned score",
    )


class ServerBenchmarkSummary(BaseModel):
    """Aggregated performance, latency, and scoring metrics for an Ollama backend server."""

    server: str
    generation_duration_avg: float = Field(default=0.0, ge=0.0)
    evaluation_duration_avg: float = Field(default=0.0, ge=0.0)
    total_duration_seconds: float = Field(default=0.0, ge=0.0)
    tasks_generated_count: int = Field(default=0, ge=0)
    evaluations_performed_count: int = Field(default=0, ge=0)
    avg_score_awarded: float = Field(default=0.0, ge=0.0, le=100.0)
    server_score_bias: float = Field(
        default=0.0,
        description="Average difference between scores given on this server vs overall consensus",
    )
    model_latencies: dict[str, float] = Field(
        default_factory=dict,
        description="Average generation duration per model on this server",
    )


class BenchmarkReport(BaseModel):
    """Complete execution payload and leaderboards for a benchmark run."""

    session_id: str
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))
    models_evaluated: list[str]
    tasks_run: list[BenchmarkTask]
    responses: list[TaskResponse] = Field(default_factory=list)
    peer_grades: list[PeerGrade] = Field(default_factory=list)
    leaderboard: list[ModelBenchmarkSummary] = Field(default_factory=list)
    server_benchmarks: list[ServerBenchmarkSummary] = Field(default_factory=list)
    is_dry_run: bool = False


class EmbeddingBenchmarkResult(BaseModel):
    """Evaluation metrics and benchmark performance for an embedding model."""

    model: str
    server: str = ""
    dimension: int = Field(default=0, ge=0)
    recall_at_1: float = Field(default=0.0, ge=0.0, le=100.0)
    recall_at_3: float = Field(default=0.0, ge=0.0, le=100.0)
    recall_at_5: float = Field(default=0.0, ge=0.0, le=100.0)
    mrr: float = Field(default=0.0, ge=0.0, le=1.0)
    ndcg_at_5: float = Field(default=0.0, ge=0.0, le=1.0)
    mean_cosine_margin: float = Field(default=0.0)
    separation_score: float = Field(default=0.0)
    latency_ms_p50: float = Field(default=0.0, ge=0.0)
    latency_ms_p95: float = Field(default=0.0, ge=0.0)
    throughput_items_per_sec: float = Field(default=0.0, ge=0.0)
    throughput_chars_per_sec: float = Field(default=0.0, ge=0.0)
    overall_score: float = Field(default=0.0, ge=0.0, le=100.0)
    is_normalized: bool = True
    category_accuracies: dict[str, float] = Field(default_factory=dict)
    memory_kb_per_vector: float = Field(default=0.0, ge=0.0)


class EmbeddingServerSummary(BaseModel):
    """Aggregated performance metrics for an embedding model backend server."""

    server: str
    avg_latency_p50_ms: float = Field(default=0.0, ge=0.0)
    avg_throughput_items_per_sec: float = Field(default=0.0, ge=0.0)
    models_evaluated_count: int = Field(default=0, ge=0)
    fastest_model: str = ""
    top_score_model: str = ""


class EmbeddingBenchmarkReport(BaseModel):
    """Consolidated benchmark report for multiple embedding models."""

    session_id: str
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))
    models: list[EmbeddingBenchmarkResult] = Field(default_factory=list)
    server_benchmarks: list[EmbeddingServerSummary] = Field(default_factory=list)
    recommendations: list[str] = Field(default_factory=list)
    is_dry_run: bool = False


class BenchmarkSuiteCase(BaseModel):
    """Evaluation test case grounded in verified or invalidated review findings."""

    model_config = ConfigDict(frozen=True)

    case_id: str
    persona: str = "devsecops"
    title: str
    severity: str = "medium"
    location: str = ""
    description: str = ""
    code_snippet: str = ""
    ground_truth_status: str = "VALIDATED"
    is_vulnerability: bool = True
    invalidation_reason: str | None = None
    expected_finding: str | None = None


class BenchmarkSuiteEvaluation(BaseModel):
    """Outcome of evaluating a single test case with a candidate model."""

    model: str
    case_id: str
    persona: str
    predicted_vulnerability: bool
    confidence_score: float = Field(default=0.0, ge=0.0, le=1.0)
    model_output: str = ""
    generated_code: str | None = None
    is_true_positive: bool = False
    is_false_positive: bool = False
    is_true_negative: bool = False
    is_false_negative: bool = False
    complexity_score: int | None = None
    nesting_depth: int | None = None
    invariant_compliant: bool = True
    latency_ms: float = Field(default=0.0, ge=0.0)
    tokens_generated: int = Field(default=0, ge=0)
    tokens_per_second: float = Field(default=0.0, ge=0.0)


class ModelSuiteMetrics(BaseModel):
    """Aggregated quantitative performance metrics for a model across the benchmark suite."""

    model: str
    provider: str = "ollama"
    server: str = ""
    total_cases: int = Field(default=0, ge=0)
    true_positives: int = Field(default=0, ge=0)
    false_positives: int = Field(default=0, ge=0)
    true_negatives: int = Field(default=0, ge=0)
    false_negatives: int = Field(default=0, ge=0)
    precision: float = Field(default=0.0, ge=0.0, le=1.0)
    recall: float = Field(default=0.0, ge=0.0, le=1.0)
    f1_score: float = Field(default=0.0, ge=0.0, le=1.0)
    hallucination_rate: float = Field(default=0.0, ge=0.0, le=1.0)
    accuracy: float = Field(default=0.0, ge=0.0, le=1.0)
    avg_latency_ms: float = Field(default=0.0, ge=0.0)
    avg_tokens_per_second: float = Field(default=0.0, ge=0.0)
    total_tokens: int = Field(default=0, ge=0)
    architectural_compliance_rate: float = Field(default=1.0, ge=0.0, le=1.0)
    overall_score: float = Field(default=0.0, ge=0.0, le=100.0)


class BenchmarkSuiteReport(BaseModel):
    """Consolidated evaluation suite execution payload, leaderboard, and details."""

    session_id: str
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))
    dataset_path: str = ""
    total_cases: int = Field(default=0, ge=0)
    models_evaluated: list[str] = Field(default_factory=list)
    leaderboard: list[ModelSuiteMetrics] = Field(default_factory=list)
    evaluations: list[BenchmarkSuiteEvaluation] = Field(default_factory=list)
    recommendations: list[str] = Field(default_factory=list)
    is_dry_run: bool = False
